#!/usr/bin/env python3
"""Generate the xschem schematics/symbols of RAMP_LR from ramp_lr_design.py.

Output: Design Files/RAMP/RAMP-LR/<cell>.sch and .sym, plus the testbench
tb_RAMP_LR.sch (unity-gain buffer, 50 pF load, Middlebrook loop-gain probe,
same as RAMP-Test/RamP_tb1_CP_FB.sch).  Devices are connected through net
labels; every cell starts with a title and the device sizes are visible.
"""
from pathlib import Path

import ramp_lr_design as D

OUT = Path(__file__).resolve().parents[1] / "Design Files" / "RAMP" / "RAMP-LR"
LIBDIR = "RAMP-LR"
HDR = "v {xschem version=3.4.6 file_version=1.2}\nG {}\nK {}\nV {}\nS {}\nE {}\n"
AUTHOR = "Nithin Purushothama"


def fmt(x):
    return f"{x:g}"


def _lab(x, y, net, flip, counter):
    counter[0] += 1
    return f"C {{lab_pin.sym}} {x} {y} 0 {flip} {{name=l{counter[0]} sig_type=std_logic lab={net}}}\n"


def mos(it, x, y, cnt):
    sym, model, _ = D.KINDS[it["kind"]]
    p = it["pins"]
    s = (f"C {{{sym}}} {x} {y} 0 0 {{name={it['name']}\nl={fmt(it['l'])}u\nw={fmt(it['w'])}u\nng=1\n"
         f"m={it['m']}\nmodel={model}\nspiceprefix=X\n}}\n")
    # D/S pin positions differ between nmos (D on top) and pmos (S on top)
    top, bot = ("D", "S") if it["kind"].startswith("n") else ("S", "D")
    s += f"N {x + 20} {y - 30} {x + 60} {y - 30} {{lab={p[top]}}}\n" + _lab(x + 60, y - 30, p[top], 1, cnt)
    s += f"N {x + 20} {y + 30} {x + 60} {y + 30} {{lab={p[bot]}}}\n" + _lab(x + 60, y + 30, p[bot], 1, cnt)
    s += f"N {x + 20} {y} {x + 40} {y} {{lab={p['B']}}}\n" + _lab(x + 40, y, p["B"], 1, cnt)
    s += f"N {x - 20} {y} {x - 50} {y} {{lab={p['G']}}}\n" + _lab(x - 50, y, p["G"], 0, cnt)
    return s


def two_term(it, x, y, cnt):
    sym, model, _ = D.KINDS[it["kind"]]
    a, b = list(it["pins"].values())
    if it["kind"] == "rhigh":
        attrs = (f"name={it['name']}\nw={it['w']}e-6\nl={it['l']}e-6\nmodel=rhigh\nbody={it['body']}\n"
                 f"spiceprefix=X\nb=0\nm=1\n")
    else:
        attrs = f"name={it['name']}\nmodel=cap_cmim\nw={it['w']}e-6\nl={it['l']}e-6\nm=1\nspiceprefix=X\n"
    s = f"C {{{sym}}} {x} {y} 0 0 {{{attrs}}}\n"
    s += f"N {x} {y - 30} {x} {y - 50} {{lab={a}}}\n" + _lab(x, y - 50, a, 1, cnt)
    s += f"N {x} {y + 30} {x} {y + 50} {{lab={b}}}\n" + _lab(x, y + 50, b, 1, cnt)
    return s


def sym_pins(cell):
    c = D.CELLS[cell]
    left = [p for p in c["ports"] if c["dirs"].get(p) == "in"]
    right = [p for p in c["ports"] if p not in left]
    pos = {}
    for side, x in ((left, -150), (right, 150)):
        for i, p in enumerate(side):
            pos[p] = (x, 20 * i - 20 * ((len(side) - 1) // 2))
    return pos


def write_sym(cell):
    c = D.CELLS[cell]
    pos = sym_pins(cell)
    h = max(abs(y) for _, y in pos.values()) + 30
    s = HDR.replace("K {}", 'K {type=subcircuit\nformat="@name @pinlist @symname"\ntemplate="name=x1"\n}')
    s += f"L 4 -130 {-h} 130 {-h} {{}}\nL 4 -130 {h} 130 {h} {{}}\nL 4 -130 {-h} -130 {h} {{}}\nL 4 130 {-h} 130 {h} {{}}\n"
    for p in c["ports"]:      # pin order = port order = netlist order
        x, y = pos[p]
        d = {"in": "in", "out": "out"}.get(c["dirs"].get(p), "inout")
        xi = -130 if x < 0 else 130
        s += f"L 7 {x} {y} {xi} {y} {{}}\n"
        s += f"B 5 {x - 2.5} {y - 2.5} {x + 2.5} {y + 2.5} {{name={p} dir={d}}}\n"
        tx = -125 if x < 0 else 125
        s += f"T {{{p}}} {tx} {y - 6} 0 {0 if x < 0 else 1} 0.2 0.2 {{}}\n"
    s += f"T {{@symname}} 0 {-h - 30} 0 0 0.3 0.3 {{hcenter=true}}\n"
    s += f"T {{@name}} 135 {-h - 20} 0 0 0.2 0.2 {{}}\n"
    (OUT / f"{cell}.sym").write_text(s)


def write_sch(cell):
    c = D.CELLS[cell]
    cnt = [0]
    s = HDR
    s += f"T {{{c['title']}}} 0 -260 0 0 0.6 0.6 {{}}\n"
    s += ("T {Generated by layout/gen_schematics.py from layout/ramp_lr_design.py - edit the design "
          "file, not this schematic} 0 -200 0 0 0.3 0.3 {}\n")
    # ports
    for i, p in enumerate(c["ports"]):
        kind = {"in": "ipin", "out": "opin"}.get(c["dirs"].get(p), "iopin")
        s += f"C {{{kind}.sym}} -300 {i * 40} 0 0 {{name=p{i + 1} lab={p}}}\n"
    # instances are wider than primitives: give them their own, wider grid
    cols = 4 if any(it["kind"] == "inst" for it in c["items"]) else 5
    px_, py_ = (640, 320) if cols == 4 else (330, 220)
    for k, it in enumerate(c["items"]):
        x, y = 100 + (k % cols) * px_, 40 + (k // cols) * py_
        if it["kind"] == "inst":
            pos = sym_pins(it["cell"])
            # rail-tied dummies: the IHP LVS deck purges shorted devices from the
            # layout netlist, so the dummy cell is excluded from the LVS netlist
            extra = " lvs_ignore=open" if it["cell"] == "DUMMY_LR" else ""
            s += f"C {{{LIBDIR}/{it['cell']}.sym}} {x + 100} {y} 0 0 {{name={it['name']}{extra}}}\n"
            for p, (px, py) in pos.items():
                net = it["conn"][p]
                ex = px + (-30 if px < 0 else 30)
                s += f"N {x + 100 + px} {y + py} {x + 100 + ex} {y + py} {{lab={net}}}\n"
                s += _lab(x + 100 + ex, y + py, net, 0 if px < 0 else 1, cnt)
        elif it["kind"] in ("rhigh", "cmim"):
            s += two_term(it, x, y, cnt)
        else:
            s += mos(it, x, y, cnt)
    rows = (len(c["items"]) + cols - 1) // cols
    s += f"C {{title.sym}} 0 {120 + rows * py_} 0 0 {{name=l0 author=\"{AUTHOR}\"}}\n"
    (OUT / f"{cell}.sch").write_text(s)


TB = r"""T {Unity-gain buffer, 50 pF load, Middlebrook double-injection loop gain (as RamP_tb1_CP_FB.sch)} -300 -760 0 0 0.4 0.4 {}
C {vsource.sym} 700 -300 0 0 {name=V2 value="dc 1.65 ac 0" savecurrent=false}
C {lab_pin.sym} 700 -330 0 0 {name=l7 sig_type=std_logic lab=VDD}
C {gnd.sym} 700 -270 0 0 {name=l8 lab=GND}
C {vsource.sym} 800 -300 0 0 {name=V1 value="dc 0.825 ac 0" savecurrent=false}
C {lab_pin.sym} 800 -330 0 0 {name=l9 sig_type=std_logic lab=VICM}
C {gnd.sym} 800 -270 0 0 {name=l10 lab=GND}
C {isource.sym} 900 -300 0 0 {name=I_BIAS value=1u}
C {lab_pin.sym} 900 -330 0 0 {name=l11 sig_type=std_logic lab=VDD}
C {lab_pin.sym} 900 -270 0 0 {name=l12 sig_type=std_logic lab=IBIAS}
C {capa.sym} 1000 -300 0 0 {name=C1 m=1 value=50p footprint=1206 device="ceramic capacitor"}
C {lab_pin.sym} 1000 -330 0 0 {name=l13 sig_type=std_logic lab=out}
C {gnd.sym} 1000 -270 0 0 {name=l14 lab=GND}
C {vsource.sym} 1150 -420 1 1 {name=Vprobe2 value=0 savecurrent=false}
C {vsource.sym} 1290 -420 3 0 {name=Vprobe1 value="dc 0 ac 1" savecurrent=false}
C {isource.sym} 1220 -490 0 0 {name=Iprobe1 value="dc 0 ac 0"}
N 1120 -420 1080 -420 {lab=inp}
N 1180 -420 1260 -420 {lab=probe}
N 1320 -420 1360 -420 {lab=out}
N 1220 -460 1220 -420 {lab=probe}
C {lab_pin.sym} 1080 -420 0 0 {name=l15 sig_type=std_logic lab=inp}
C {lab_pin.sym} 1360 -420 0 1 {name=l16 sig_type=std_logic lab=out}
C {lab_pin.sym} 1220 -420 3 0 {name=l17 sig_type=std_logic lab=probe}
C {gnd.sym} 1220 -520 2 0 {name=l18 lab=GND}
C {code_shown.sym} -300 -660 0 0 {name=MODELS only_toplevel=true value="
** IHP SG13G2 models (TT)
.lib cornerMOSlv.lib mos_tt
.lib cornerMOShv.lib mos_tt
.lib cornerRES.lib res_typ
.lib cornerCAP.lib cap_typ
"}
C {code_shown.sym} 300 -660 0 0 {name=NGSPICE only_toplevel=true value="
.control
ac dec 40 1 10G
alter @Vprobe1[acmag]=0
alter @Iprobe1[acmag]=1
ac dec 40 1 10G
let mb = 1/(ac1.v(probe) + ac2.i(Vprobe2)) - 1
let phase_mb = 180/PI*vp(mb)
meas ac ugf when vdb(mb)=0
meas ac pm_deg find phase_mb when vdb(mb)=0
meas ac loop_gain find vdb(mb) at=1
let phase_margin = 180 + pm_deg
print phase_margin
plot vdb(mb) phase_mb
.endc
"}
"""


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    D.check_rows()
    for cell in D.CELLS:
        write_sch(cell)
        write_sym(cell)
    tb = f"C {{{LIBDIR}/RAMP_LR.sym}} 300 -300 0 0 {{name=x1}}\n"
    conn = dict(VDD="VDD", GND="GND", IBIAS="IBIAS", minus="VICM", plus="inp", Vout="out")
    cnt = [100]
    for p, (px, py) in sym_pins("RAMP_LR").items():
        ex = px + (-40 if px < 0 else 40)
        tb += f"N {300 + px} {-300 + py} {300 + ex} {-300 + py} {{lab={conn[p]}}}\n"
        tb += _lab(300 + ex, -300 + py, conn[p], 0 if px < 0 else 1, cnt)
    (OUT / "tb_RAMP_LR.sch").write_text(
        HDR + tb + TB + f"C {{title.sym}} -300 0 0 0 {{name=l0 author=\"{AUTHOR}\"}}\n")
    print(f"wrote {len(D.CELLS)} cells + testbench to {OUT}")


if __name__ == "__main__":
    main()
